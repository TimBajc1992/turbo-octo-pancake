export const byId = (id: string) => catalog.find((c) => c.id === id);

export const normalizeExerciseName = (value: string) =>
  value
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, " ")
    .trim();

/** Exact aliases only. Identifying a movement never edits a historical record. */
export function candidateForExercise(
  e: Pick<Exercise, "id" | "name" | "coach"> & Partial<Pick<Exercise, "mode">>,
): Candidate | undefined {
  if (e.coach?.catalogId) return byId(e.coach.catalogId);
  const identified = byId(e.id);
  if (
    identified &&
    (!e.mode ||
      e.mode === "unknown" ||
      e.mode === (identified.mode ?? "machine"))
  )
    return identified;
  const name = normalizeExerciseName(e.name);
  return catalog.find(
    (c) =>
      (!e.mode || e.mode === "unknown" || e.mode === (c.mode ?? "machine")) &&
      [c.name, ...(c.aliases ?? [])].some(
        (alias) => normalizeExerciseName(alias) === name,
      ),
  );
}

export function loadLabel(c: Candidate): string {
  if (c.id === "goblet_squat" || c.id === "dumbbell_overhead_extension")
    return "kg ene uteži";
  return c.mode === "dumbbell"
    ? "kg ene ročke"
    : c.mode === "barbell"
      ? "kg skupaj s palico"
      : c.mode === "bodyweight"
        ? "dodatni kg"
        : c.mode === "assisted"
          ? "kg pomoči"
          : "kg na napravi";
}
